import {writeFileSync} from 'node:fs';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {connectMascot} from './android_mascot_cdp.mjs';
import {serial,find,nodes,wait,screenshot} from './android_mascot_ui.mjs';
const bounds=find('Mulai Tantangan').center;
const connection=await connectMascot();await connection.command('Runtime.enable');
await connection.evaluate("document.querySelector('model-viewer').addEventListener('pause',()=>console.log('KIFC_MASCOT_PAUSED'));true");
const paused=connection.evaluate(`(async()=>{const v=document.querySelector('model-viewer');for(let i=0;i<200;i++){if(v.paused)return {paused:true,time:v.currentTime};await new Promise(r=>setTimeout(r,20));}return {paused:v.paused};})()`).catch(error=>({targetClosed:true,detail:String(error)}));
await wait(70);
await promisify(execFile)('adb',['-s',serial,'shell','input','tap',...bounds.map(x=>String(Math.round(x)))]);
const stopped=await paused;
const pauseEvent=connection.events.some(e=>e.method==='Runtime.consoleAPICalled'&&e.params.args.some(a=>a.value==='KIFC_MASCOT_PAUSED'));
connection.close();
if(!stopped.paused&&!stopped.targetClosed&&!pauseEvent)throw new Error('Welcome remained active '+JSON.stringify({stopped,pauseEvent}));
await wait(1200);
const next=await connectMascot();
const state=await next.evaluate(`(()=>{const v=document.querySelector('model-viewer');return {loaded:v.loaded,clip:v.animationName,paused:v.paused};})()`);next.close();
if(!state.loaded||state.clip!=='PointIdle'||state.paused)throw new Error(JSON.stringify(state));
screenshot('assembly');
writeFileSync('docs/client-revisions/2026-11-02/r30-16/android-start-navigation.json',JSON.stringify({stopped,pauseEvent,state,controls:nodes().filter(n=>n.label).map(n=>({label:n.label,bounds:n.bounds}))},null,2));
console.log(JSON.stringify({stopped,pauseEvent,state}));
